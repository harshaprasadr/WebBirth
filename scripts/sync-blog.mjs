// Pulls the latest posts from blog.webbirth.in (WordPress REST API), saves resized
// cover images to public/blog/ and writes src/data/posts.ts.
// Usage: npm run sync:blog            (default 6 posts)
//        npm run sync:blog -- 9       (custom count)
import { mkdir, readdir, unlink, writeFile } from 'node:fs/promises'
import path from 'node:path'
import sharp from 'sharp'

const COUNT = Number(process.argv[2] ?? 6)
const API = `https://blog.webbirth.in/wp-json/wp/v2/posts?per_page=${COUNT}&_embed=wp:featuredmedia&_fields=date,slug,link,title,excerpt,content,_links,_embedded`
const OUT_IMG = path.resolve('public/blog')
const OUT_DATA = path.resolve('src/data/posts.ts')

const decode = (s) =>
  s
    .replace(/<[^>]+>/g, ' ')
    .replace(/&#8217;|&rsquo;/g, '’')
    .replace(/&#8216;|&lsquo;/g, '‘')
    .replace(/&#8220;|&ldquo;/g, '“')
    .replace(/&#8221;|&rdquo;/g, '”')
    .replace(/&#8211;|&ndash;/g, '–')
    .replace(/&#8212;|&mdash;/g, '—')
    .replace(/&#038;|&amp;/g, '&')
    .replace(/&nbsp;|&#160;/g, ' ')
    .replace(/&hellip;|&#8230;|\[…\]|\[&hellip;\]/g, '…')
    .replace(/\s+/g, ' ')
    .trim()

// WordPress categories on this blog are "Uncategorized", so derive a topic from the title.
const topics = [
  [/ui|ux|design|landing/i, 'Design'],
  [/mobile|app\b|apps\b/i, 'Mobile Apps'],
  [/web application|custom web/i, 'Web Apps'],
  [/seo|search|keyword|ranking|backlink/i, 'SEO'],
  [/brand|colour|color/i, 'Branding'],
  [/marketing|social|whatsapp|lead|conversion|content/i, 'Marketing'],
  [/website|web|ssl|static|dynamic|accessib/i, 'Web'],
]
const topicOf = (title) => topics.find(([re]) => re.test(title))?.[1] ?? 'Insights'

const res = await fetch(API)
if (!res.ok) throw new Error(`Blog API ${res.status}`)
const raw = await res.json()

await mkdir(OUT_IMG, { recursive: true })
for (const f of await readdir(OUT_IMG)) await unlink(path.join(OUT_IMG, f))

const posts = []
for (const p of raw) {
  const title = decode(p.title.rendered)
  // Excerpts on this blog start by repeating the title — strip it.
  let excerpt = decode(p.excerpt.rendered)
  if (excerpt.toLowerCase().startsWith(title.toLowerCase())) excerpt = excerpt.slice(title.length).trim()
  excerpt = excerpt.replace(/\s*…$/, '')
  if (excerpt.length > 170) excerpt = excerpt.slice(0, excerpt.lastIndexOf(' ', 165)) + '…'
  const words = decode(p.content.rendered).split(' ').length

  let image
  const media = p._embedded?.['wp:featuredmedia']?.[0]?.source_url
  if (media) {
    const buf = Buffer.from(await (await fetch(media)).arrayBuffer())
    image = `/blog/${p.slug}.webp`
    await sharp(buf).resize({ width: 960, withoutEnlargement: true }).webp({ quality: 78 }).toFile(path.join(OUT_IMG, `${p.slug}.webp`))
  }

  posts.push({
    slug: p.slug,
    title,
    excerpt,
    date: p.date.slice(0, 10),
    url: p.link,
    topic: topicOf(title),
    readingMinutes: Math.max(2, Math.round(words / 220)),
    ...(image ? { image } : {}),
  })
  console.log('→', posts.at(-1).date, title)
}

const file = `// Generated by scripts/sync-blog.mjs from blog.webbirth.in — run \`npm run sync:blog\` to refresh.
export type Post = {
  slug: string
  title: string
  excerpt: string
  /** ISO date (YYYY-MM-DD) */
  date: string
  url: string
  topic: string
  readingMinutes: number
  image?: string
}

export const blogUrl = 'https://blog.webbirth.in/'

export const posts: Post[] = ${JSON.stringify(posts, null, 2)}
`
await writeFile(OUT_DATA, file)
console.log(`Wrote ${posts.length} posts`)
